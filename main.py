# Функція приймає текст і повертає кількість слів у ньому
def count_words(text: str) -> int:
    # Якщо текст порожній або не переданий, повертаємо 0
    if not text:
        return 0
    # Розбиваємо текст за пробілами та рахуємо кількість елементів
    return len(text.split())


# Функція для перевірки, чи містить текст лише літери (без цифр)
def is_text_alpha(text: str) -> bool:
    # Видаляємо пробіли та перевіряємо, чи залишилися лише літери
    return text.replace(" ", "").isalpha()
